a=[]

while True:
    b=float(input(f'При вводе нуля программа завершит работу и выведет результат \nВведите любое действительное число: \n'))
    
    if b!=0:
        a.append(b)
        continue
    
    else:
        c=max(a)
        print(f'Наибольшее число в этой последовательности: {c}')
        break